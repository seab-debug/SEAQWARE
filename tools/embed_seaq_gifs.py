#!/usr/bin/env python3
"""Generate src/core/seaq_gifs_data.cpp from embedded_resources/seaq_gifs/*.gif.

Every GIF except screensaver.gif goes into the GIFs page playlist (alphabetical).
screensaver.gif becomes the built-in idle screensaver.
Run from the repo root:  python3 tools/embed_seaq_gifs.py
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'embedded_resources', 'seaq_gifs')
OUT = os.path.join(ROOT, 'src', 'core', 'seaq_gifs_data.cpp')

def ident(name):
    return 'seaq_gif_' + re.sub(r'[^0-9a-zA-Z]', '_', name)

def array(name, data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append('    ' + ','.join(f'0x{b:02x}' for b in data[i:i + 24]) + ',')
    return f'static const uint8_t {ident(name)}[] PROGMEM = {{\n' + '\n'.join(lines) + '\n};\n'

files = sorted(f for f in os.listdir(SRC) if f.lower().endswith('.gif'))
playlist = [f for f in files if f.lower() != 'screensaver.gif']
has_saver = 'screensaver.gif' in files

out = ['// AUTOGENERATED by tools/embed_seaq_gifs.py - edit embedded_resources/seaq_gifs instead.',
       '#include "seaq_gifs.h"', '', '#if !defined(LITE_VERSION)', '']
total = 0
for f in files:
    data = open(os.path.join(SRC, f), 'rb').read()
    total += len(data)
    out.append(array(f[:-4], data))
out.append('const EmbeddedGif SEAQ_GIFS[] = {')
for f in playlist:
    out.append(f'    {{"{f[:-4]}", {ident(f[:-4])}, sizeof({ident(f[:-4])})}},')
out.append('};')
out.append(f'const int SEAQ_GIFS_COUNT = {len(playlist)};')
if has_saver:
    out.append(f'const EmbeddedGif SEAQ_SCREENSAVER = {{"screensaver", {ident("screensaver")}, sizeof({ident("screensaver")})}};')
else:
    out.append('const EmbeddedGif SEAQ_SCREENSAVER = {"", nullptr, 0};')
out += ['', '#endif', '']
open(OUT, 'w').write('\n'.join(out))
print(f'{len(playlist)} playlist GIFs + {"1 screensaver" if has_saver else "no screensaver"}, {total} bytes -> {os.path.relpath(OUT, ROOT)}')
